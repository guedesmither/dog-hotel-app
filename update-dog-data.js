async function main() {
  for (const data of dogData) {
    try {
      // Buscar pelo nome (case insensitive)
      const dog = await prisma.dog.findFirst({ 
        where: { name: { contains: data.name, mode: 'insensitive' } }
      })
      
      if (!dog) {
        console.log(`⚠️  Cão ${data.name} não encontrado`)
        continue
      }

      await prisma.dog.update({
        where: { id: dog.id },
        data: {
          scheduledDays: data.scheduledDays,
          serviceType: data.serviceType,
          feedingType: data.feedingType,
          feedingInstructions: data.feedingInstructions,
          feedingTimesPerDay: data.feedingTimesPerDay ? String(data.feedingTimesPerDay) : null,
          feedingGramsPerMeal: data.feedingGramsPerMeal ? String(data.feedingGramsPerMeal) : null,
          allergies: data.allergies,
          medications: data.medications,
          vetName: data.vetName,
          allowPool: data.allowPool,
          allowPhotos: data.allowPhotos,
          ownerPhone: data.ownerPhone,
          ownerEmail: data.ownerEmail,
          ownerCpf: data.ownerCpf,
        },
      })
      
      console.log(`✅ ${dog.name} atualizado`)
    } catch (error) {
      console.error(`❌ Erro ao atualizar ${data.name}:`, error.message)
    }
  }
  
  console.log('\n✅ Atualização concluída!')
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
